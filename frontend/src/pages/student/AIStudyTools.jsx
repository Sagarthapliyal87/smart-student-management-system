import { useState } from 'react';
import { useAuth } from '../../context/AuthContext';
import useFetch from '../../hooks/useFetch';
import AIBox, { AIStatusBanner } from '../../components/AIBox';
import PageHeader from '../../components/PageHeader';

export default function StudentAIStudyTools() {
  const { user } = useAuth();
  const { data: status } = useFetch('/ai/status');
  const { data: subjectsData } = useFetch(user.student?.classId ? `/academics/subjects?classId=${user.student.classId}` : null);
  const [question, setQuestion] = useState('');
  const [doubt, setDoubt] = useState('');
  const [source, setSource] = useState('');
  const [plan, setPlan] = useState({ examDate: '', hours: 3, subjects: [], weak: [] });
  const subjects = (subjectsData || []).map((s) => s.name);
  const toggle = (key, name) => setPlan((p) => ({ ...p, [key]: p[key].includes(name) ? p[key].filter((x) => x !== name) : [...p[key], name] }));
  const off = status && !status.configured;

  return (
    <>
      <PageHeader title="AI study tools" subtitle="Answers are generated by an AI model and can contain mistakes. Verify important facts." />
      <AIStatusBanner configured={status?.configured} />
      <AIBox title="AI study assistant" description="Ask for an explanation of any topic, e.g. 'Explain normalization in DBMS'." submitLabel="Ask" disabled={off}
        buildRequest={() => (question.trim() ? { url: '/ai/study-assistant', body: { question } } : { error: 'Type a question first.' })}>
        <textarea rows={3} className="input-field" value={question} onChange={(e) => setQuestion(e.target.value)} placeholder="Explain normalization in DBMS" />
      </AIBox>
      <AIBox title="AI doubt solver" description="Describe a specific problem you are stuck on." submitLabel="Solve" disabled={off}
        buildRequest={() => (doubt.trim() ? { url: '/ai/doubt-solver', body: { question: doubt } } : { error: 'Describe your doubt first.' })}>
        <textarea rows={3} className="input-field" value={doubt} onChange={(e) => setDoubt(e.target.value)} placeholder="What is polymorphism in C++?" />
      </AIBox>
      <AIBox title="AI notes generator" description="Paste your study material to get short notes, key points, revision questions and MCQs." disabled={off}
        buildRequest={() => (source.trim().length > 50 ? { url: '/ai/notes-generator', body: { sourceText: source } } : { error: 'Paste at least a few sentences of study material.' })}>
        <textarea rows={6} className="input-field" value={source} onChange={(e) => setSource(e.target.value)} placeholder="Paste text from your notes or textbook here..." />
      </AIBox>
      <AIBox title="AI study planner" description="Get a day-by-day plan based on your exam date, subjects and weak areas." submitLabel="Create plan" disabled={off}
        buildRequest={() => (!plan.examDate || !plan.subjects.length ? { error: 'Choose an exam date and at least one subject.' }
          : { url: '/ai/study-planner', body: { examDate: plan.examDate, subjects: plan.subjects, weakSubjects: plan.weak, availableHoursPerDay: plan.hours } })}>
        <div className="grid sm:grid-cols-2 gap-3">
          <div><label className="label">Exam date</label><input type="date" className="input-field" value={plan.examDate} onChange={(e) => setPlan({ ...plan, examDate: e.target.value })} /></div>
          <div><label className="label">Study hours per day</label><input type="number" min="1" max="12" className="input-field" value={plan.hours} onChange={(e) => setPlan({ ...plan, hours: e.target.value })} /></div>
        </div>
        <div><p className="label">Subjects (tap to select · double-tap star marks weak)</p>
          <div className="flex flex-wrap gap-2">{subjects.map((s) => (
            <span key={s} className="inline-flex">
              <button type="button" onClick={() => toggle('subjects', s)} className={`px-3 py-1 rounded-l-full text-sm border ${plan.subjects.includes(s) ? 'bg-brand-600 text-white border-brand-600' : 'bg-white border-gray-200 text-gray-600'}`}>{s}</button>
              <button type="button" title="Mark as weak subject" onClick={() => toggle('weak', s)} className={`px-2 rounded-r-full text-sm border ${plan.weak.includes(s) ? 'bg-amber-400 border-amber-400' : 'bg-white border-gray-200 text-gray-400'}`}>★</button>
            </span>
          ))}</div></div>
      </AIBox>
      <AIBox title="AI performance analysis" description="Analyzes your recorded marks and gives specific suggestions." submitLabel="Analyze my performance" disabled={off}
        buildRequest={() => ({ method: 'GET', url: '/ai/performance-analysis' })} />
    </>
  );
}
